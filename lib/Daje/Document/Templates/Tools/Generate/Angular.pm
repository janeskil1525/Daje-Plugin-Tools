my $set_datatype = sub {
    my $datatype = $_[0];
    my $result = "string";
    if (uc($datatype) eq 'BIGINT') {
        $result = 'number';
    }
    elsif (uc($datatype) eq 'NUMERIC') {
        $result = 'number';
    }
    elsif (uc($datatype) eq 'BOOLEAN') {
        $result = 'boolean';
    }
    elsif (uc($datatype) eq 'MONEY') {
        $result = 'number';
    }

    return $result;
};

my $make_interface_name = sub {
    my $project = $_[0];
    my $table = $_[1];
    my $list = $_[2];
    $list = 0 unless defined $list;
    return ucfirst($project) . ucfirst($table) . "ListInterface" if ($list == 1);
    return ucfirst($project) . ucfirst($table) . "Interface";
};

my $ufirst = sub {
    return ucfirst($_[0]);
};

sub set_subs($self) {
    $self->insert_sub('set_datatype', $set_datatype);
    $self->insert_sub('make_interface_name', $make_interface_name);
    $self->insert_sub('ufirst', $ufirst);
}

1;

